show <- function(label, expr) { w <- NULL; r <- withCallingHandlers(tryCatch(expr, error = function(e) paste0("ERR<", class(e)[1], "> ", conditionMessage(e))), warning = function(x) { w <<- conditionMessage(x); invokeRestart("muffleWarning") }); if (is.function(r)) r <- "FUNCTION"; cat(sprintf("%-34s %s%s\n", label, paste(deparse(r, control = c("digits17", "keepNA", "keepInteger", "showAttributes")), collapse = ""), if (is.null(w)) "" else paste("  WARN:", w))) }
