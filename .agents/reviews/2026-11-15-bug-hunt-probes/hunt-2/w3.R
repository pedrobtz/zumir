source("common.R")
tier <- commandArgs(TRUE)[1]
cs <- cfunction("void cs(int n, const double *x, double *y) { double s = 0; for (int i = 0; i < n; i++) { s += x[i]; y[i] = s; } }", out = "y", n = "n", tier = tier)
show("basic", cs(x = c(1, 2, 3)))
show("n = 0 via empty x", try_(cs(x = numeric(0))))
show("n given smaller", try_(cs(n = 2, x = c(1, 2, 3))))
show("n given equal", try_(cs(n = 3L, x = c(1, 2, 3))))
show("n given larger", try_(cs(n = 4, x = c(1, 2, 3))))
show("n = 0 given", try_(cs(n = 0, x = c(1, 2, 3))))
show("n = -1", try_(cs(n = -1, x = c(1, 2, 3))))
show("n = NA", try_(cs(n = NA, x = c(1, 2, 3))))
show("n = 2.5", try_(cs(n = 2.5, x = c(1, 2, 3))))
show("n = 2^31", try_(cs(n = 2^31, x = c(1, 2, 3))))
show("x integer", try_(cs(x = 1:3)))
show("x logical", try_(cs(x = c(TRUE, FALSE))))
show("x character", try_(cs(x = "a")))
show("x factor", try_(cs(x = factor(c("b", "a", "b")))))
show("x Date", try_(cs(x = Sys.Date() + 0:1)))
show("x matrix (attributes on output?)", try_(cs(x = matrix(1:4, 2))))
show("x with NA", try_(cs(x = c(1, NA, 3))))
show("x list", try_(cs(x = list(1, 2))))
show("x NULL", try_(cs(x = NULL)))
y0 <- c(10, 20, 30); r <- cs(x = c(1, 2, 3), y = y0); show("y supplied: result", r); show("y supplied: caller's y0 unchanged", y0)
show("y supplied shorter", try_(cs(x = c(1, 2, 3), y = c(0, 0))))
show("y supplied longer keeps tail", try_(cs(x = c(1, 2, 3), y = c(9, 9, 9, 9, 9))))
show("y supplied integer", try_(cs(x = c(1, 2, 3), y = 1:3)))
show("y supplied with names", try_(cs(x = c(a = 1, b = 2), y = c(p = 0, q = 0))))
x1 <- c(1, 2, 3); r <- cs(x = x1, y = x1); show("same vector as x and y", list(r = r, x1 = x1))
# int pointers
ip <- cfunction("int ip(int n, const int *a, int *b) { int s = 0; for (int i = 0; i < n; i++) { b[i] = a[i] * 2; s += a[i]; } return s; }", out = "b", n = "n", tier = tier)
show("int basic", ip(a = 1:3))
show("int from double", try_(ip(a = c(1, 2, 3))))
show("int from 1.5", try_(ip(a = c(1, 1.5))))
show("int from 2^31-1", try_(ip(a = 2147483647)))
show("int from 2^31", try_(ip(a = 2147483648)))
show("int from -2^31", try_(ip(a = -2147483648)))
show("int from NA_real_", try_(ip(a = NA_real_)))
show("int NA_integer_ in (NA*2 wraps)", try_(ip(a = NA_integer_)))
show("int from NaN/Inf", try_(ip(a = c(NaN, Inf))))
show("int out supplied double non-whole", try_(ip(a = 1:2, b = c(0.5, 1))))
a0 <- 1:3; r <- ip(a = a0, b = a0); show("alias int", list(r = r, a0 = a0))
# fixed out
fx <- cfunction("void fx(double v, double *o) { o[0] = v; o[1] = -v; o[2] = v * 2; }", out = c(o = 3), tier = tier)
show("fixed out", fx(2)); show("fixed out supplied short", try_(fx(2, o = c(0, 0)))); show("fixed out supplied long", try_(fx(2, o = 1:5 + 0)))
show("fixed 0", try_(cfunction("int z(double *o) { return o == 0; }", out = c(o = 0), tier = tier)()))
show("empty const pointer is NULL", try_(cfunction("int z(const double *o) { return o == 0; }", tier = tier)(numeric(0))))
for (o in list(c(o = -1), c(o = 1.5), c(o = NA), c(o = 2^31), c(o = Inf), "nope", c("o", "o"), list("o", o = 3), 3, c(3), NULL, NA, character(0)))
  show(paste("out =", paste(deparse(o), collapse = "")), { r <- try_(cfunction("void fx(double v, double *o) { o[0] = v; }", out = o, n = NULL, tier = tier)); if (inherits(r, "caught")) r else "compiled" })
for (nn in list("v", "o", "zz", NA_character_, c("a", "b"), 1, ""))
  show(paste("n =", deparse(nn)), { r <- try_(cfunction("void fx(double v, double *o) { o[0] = v; }", out = c(o = 1), n = nn, tier = tier)); if (inherits(r, "caught")) r else "compiled" })
