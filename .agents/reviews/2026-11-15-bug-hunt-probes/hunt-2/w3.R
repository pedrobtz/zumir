  show(paste("src:", gsub("\n", "\\\\n", substr(src, 1, 70))), { r <- try_(cfunction(src, tier = tier)); if (inherits(r, "caught")) r else paste("compiled:", paste(format(try_(r(1))), collapse = " ")) })
