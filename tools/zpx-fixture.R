# Writes tests/consumer/tests/testthat/fixtures/zpx-models.R: the IR that
# zupmxode compiles for three models, which the consumer lowers through
# zumir's C API the way zupmxode does and checks against zupmxode's own
# reference evaluator (tests/consumer/src/zpx.c).
#
# Run from zumir's root with zupmxode installed, and its checkout at
# ZUPMXODE_DIR (default ../zupmxode) for the corpus models:
#
#   Rscript tools/zpx-fixture.R
#
# Regenerate when zupmxode's IR format changes (ZPX_IR_VERSION), and port
# its lowering and evaluator again in the same change.
library(zupmxode)

dir <- Sys.getenv("ZUPMXODE_DIR", "../zupmxode")
commit <- system2(
  "git",
  c("-C", dir, "rev-parse", "--short", "HEAD"),
  stdout = TRUE
)
corpus <- file.path(dir, "tests/testthat/fixtures/oracle/models")

sources <- list(
  # Two library models from zupmxode's oracle corpus.
  lib_PK_2cmt_des = readLines(file.path(corpus, "lib_PK_2cmt_des.R")),
  lib_PK_2cmt_tdcl_des = readLines(file.path(corpus, "lib_PK_2cmt_tdcl_des.R")),
  # No corpus model branches: a lag time and an Emax effect, for the
  # comparisons, `&&` and the jumps.
  lag_emax = c(
    "ka <- exp(lka)",
    "cl <- exp(lcl)",
    "v <- exp(lv)",
    "emax <- exp(lemax)",
    "ec50 <- exp(lec50)",
    "if (t > tlag && depot > 0) {",
    "  abs <- ka * depot",
    "} else {",
    "  abs <- 0",
    "}",
    "d/dt(depot) <- -abs",
    "d/dt(central) <- abs - cl / v * central",
    "cp <- central / v",
    "eff <- emax * cp^hill / (ec50^hill + cp^hill)"
  )
)

models <- lapply(sources, function(src) {
  m <- pmx_ode_model(paste(src, collapse = "\n"))
  list(
    source = src,
    states = m$states,
    params = m$params,
    code = m$ir$code,
    consts = m$ir$consts
  )
})

out <- "tests/consumer/tests/testthat/fixtures/zpx-models.R"
con <- file(out, "w")
writeLines(
  c(
    sprintf(
      "# Generated by tools/zpx-fixture.R from zupmxode %s (%s); do not edit.",
      packageVersion("zupmxode"),
      commit
    ),
    "# Each model's IR: code (src/core/ir.h's int32 layout) and constants."
  ),
  con
)
dput(
  models,
  con,
  control = c(
    "keepNA",
    "keepInteger",
    "niceNames",
    "showAttributes",
    "hexNumeric"
  )
)
close(con)
cat("wrote", out, "\n")
